std::string describe(char const* cls, size_t offset) {
    auto findIn = [&](char const* name, size_t off, std::string& out) {
        for (auto const& t : kTables) {
            if (std::strcmp(t.cls, name) != 0) continue;
            Member const* best = nullptr;
            for (size_t i = 0; i < t.count; i++)
                if (t.members[i].offset <= off && (!best || t.members[i].offset >= best->offset)) best = &t.members[i];
            if (best) {
                out = best->offset == off ? fmt::format("{}::{}", name, best->name) : fmt::format("{}::{}+{}", name, best->name, off - best->offset);
                return true;
            }
        }
        return false;
    };
    auto find = [&](char const* name, size_t off, std::string& out) {
        static char const* const kChains[][4] = {
            {"PlayLayer", "GJBaseGameLayer", nullptr, nullptr},
            {"PlayerObject", "GameObject", nullptr, nullptr},
            {"EffectGameObject", "EnhancedGameObject", "GameObject", nullptr},
            {"EnhancedGameObject", "GameObject", nullptr, nullptr},
        };
        for (auto const& chain : kChains) {
            if (std::strcmp(chain[0], name) != 0) continue;
            for (int c = 0; c < 4 && chain[c]; c++) {
                size_t firstOwn = (size_t) -1;
                for (auto const& t : kTables)
                    if (std::strcmp(t.cls, chain[c]) == 0)
                        for (size_t i = 0; i < t.count; i++) firstOwn = std::min(firstOwn, t.members[i].offset);
                if (off >= firstOwn && findIn(chain[c], off, out)) return true;
            }
            return false;
        }
        return findIn(name, off, out);
    };
    std::string out;
    if (find(cls, offset, out)) {
        if (std::strcmp(cls, "PlayLayer") == 0 || std::strcmp(cls, "GJBaseGameLayer") == 0) {
            size_t gs = offsetof(GJBaseGameLayer, m_gameState);
            if (offset >= gs && offset < gs + sizeof(GJGameState)) {
                std::string inner;
                if (find("GJGameState", offset - gs, inner)) out += " = " + inner;
            }
        }
        return out;
    }
    return fmt::format("{}+{}", cls, offset);
}

size_t sizeOf(char const* cls) {
    for (auto const& t : kTables) if (std::strcmp(t.cls, cls) == 0) return t.size;
    return 0;
}

